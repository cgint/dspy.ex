  # ---------------------------------------------------------------------------
  # Row 4 — the caller's :rand state is untouched (E7)
  # ---------------------------------------------------------------------------

  # Ruling 2 (2026-10-03): compare `:rand.export_seed()` before and after.
  # `:rand.uniform/1` (the old helper) advances the state and is therefore
  # wrong. In a never-seeded process `export_seed()` stays `:undefined`.
  defp assert_rand_state_untouched(fun, label) do
    before = :rand.export_seed()
    _ = fun.()
    after_ = :rand.export_seed()

    assert before == after_,
           "caller's :rand state was consumed (#{label}): before=#{inspect(before)} after=#{inspect(after_)}"
  end

  test "row 4a: Dataset.train/1 leaves the caller's :rand state unchanged (seeded)" do
    :rand.seed(:exsss, {1, 2, 3})

    ds =
      Dspy.Dataset.new(
        train: Enum.map(0..9, fn i -> %{"v" => i} end),
        train_seed: 0,
        train_size: 7
      )

    assert_rand_state_untouched(fn -> Dspy.Dataset.train(ds) end, "train seeded")
  end

  test "row 4a: Dataset.train/1 leaves the caller's :rand state unchanged (caller never seeded)" do
    # In a never-seeded process export_seed() is :undefined; it must stay
    # unchanged after train/1 (ruling 2 unseeded shape).
    ds =
      Dspy.Dataset.new(
        train: Enum.map(0..9, fn i -> %{"v" => i} end),
        train_seed: 0,
        train_size: 7
      )

    before = :rand.export_seed()
    Dspy.Dataset.train(ds)
    after_ = :rand.export_seed()

    assert before == after_,
           "caller's :rand state changed: before=#{inspect(before)} after=#{inspect(after_)}"
  end

  test "row 4b: DataLoader.sample/3 leaves the caller's :rand state unchanged (seeded, unseeded, seed: nil)" do
    rows = ten_rows()

    :rand.seed(:exsss, {9, 8, 7})

    assert_rand_state_untouched(
      fn -> Dspy.DataLoader.sample(rows, 3, seed: 42) end,
      "sample seeded"
    )

    # unseeded shape: export_seed() stays unchanged (ruling 2)
    before = :rand.export_seed()
    result = Dspy.DataLoader.sample(rows, 3, seed: nil)
    after_ = :rand.export_seed()

    assert before == after_,
           "caller's :rand state changed: before=#{inspect(before)} after=#{inspect(after_)}"

    assert length(result) == 3
  end

  test "row 4c: train_test_split/2 leaves the caller's :rand state unchanged (seeded, unseeded, seed: nil)" do
    rows = ten_rows()

    :rand.seed(:exsss, {1, 1, 1})

    assert_rand_state_untouched(
      fn -> Dspy.DataLoader.train_test_split(rows, train_size: 0.7, seed: 0) end,
      "split seeded"
