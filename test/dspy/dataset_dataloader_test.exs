  # A Default-adapter-compatible LM answering the ChainOfThought signature
  # (reasoning + answer) as `"Ans#<n>"` for call n (1-based), recording every
  # request in :persistent_term so the caller (which may run in a different
  # process than evaluate's tasks) can read the prompts back.
  defmodule CapCoT do
    @behaviour Dspy.LM
    defstruct [:key]

    def new do
      key = {__MODULE__, System.unique_integer([:positive])}
      :persistent_term.put(key, {[], []})
      %__MODULE__{key: key}
    end

    @impl true
    def generate(%{key: key}, req) do
      {answers, reqs} = :persistent_term.get(key)
      n = length(answers) + 1
      :persistent_term.put(key, {["Ans##{n}" | answers], [prompt_of(req) | reqs]})

      content =
        "Reasoning: step by step\nAnswer: Ans##{n}"

      {:ok,
       %{
         choices: [
           %{message: %{role: "assistant", content: content}, finish_reason: "stop"}
         ],
         usage: nil
       }}
    end

    @impl true
    def supports?(_lm, _feature), do: true

    def answers(%{key: key}), do: :persistent_term.get(key) |> elem(0) |> Enum.reverse()

    def prompts(%{key: key}), do: :persistent_term.get(key) |> elem(1) |> Enum.reverse()

    defp prompt_of(req) do
      req
      |> Map.get(:messages, [])
      |> Enum.map(fn message ->
        content = Map.get(message, :content) || Map.get(message, "content")
        if is_binary(content), do: content, else: inspect(content)
      end)
      |> Enum.join("")
    end
  end

  defmodule M1eQA do
    use Dspy.Signature

    input_field(:question, :string, "Question")
    output_field(:answer, :string, "Answer")
  end

  defp qa_file(name) do
