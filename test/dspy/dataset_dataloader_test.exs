  # The judge prompt (request text) carries `Ground_truth: …` and
  # `System_response: …` in the Default adapter's wire format; a judge that
  # answers a fixed Recall/Precision scores 1.0 no matter which loaded values
  # it received — the prompt assertions below are what make MX1 red (V1,
  # pre-mortem 13).
  defmodule EchoJudge do
    @behaviour Dspy.LM
    defstruct [:key]

    # A judge (Default-adapter wire format) that answers a FIXED
    # Recall/Precision (1.0 / 1.0) and records its prompt so a test can
    # prove WHICH values the judge received: under MX1 those would be
    # blank (V1, pre-mortem 13). A fixed score keeps the assertion
    # "both key shapes score the same" meaningful even if the string
    # path blanks the values.
    def new do
      key = {__MODULE__, System.unique_integer([:positive])}
      :persistent_term.put(key, [])
      %__MODULE__{key: key}
    end

    @impl true
    def generate(%{key: key}, req) do
      prompt = prompt_of(req)
      :persistent_term.put(key, [prompt | :persistent_term.get(key)])

      {:ok,
       %{
         choices: [
           %{
             message: %{
               role: "assistant",
               content: "Reasoning: r\nRecall: 1.0\nPrecision: 1.0"
             },
             finish_reason: "stop"
           }
         ],
         usage: nil
       }}
    end

    @impl true
    def supports?(_lm, _feature), do: true

    def prompts(%{key: key}), do: :persistent_term.get(key) |> Enum.reverse()

    defp prompt_of(req) do
      req
      |> Map.get(:messages, [])
      |> Enum.map(fn message ->
        content = Map.get(message, :content) || Map.get(message, "content")
        if is_binary(content), do: content, else: inspect(content)
      end)
      |> Enum.join("")
    end
  end

