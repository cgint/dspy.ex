          Enum.map_join(1..5, "\n", fn i -> "Q##{i},R##{i},A##{i}" end)
      )

    loaded = Dspy.DataLoader.from_csv(csv_path)
    [loaded_ex | _] = loaded
    [atom_ex | _] = atom_rows(loaded)

    # A string-keyed prediction exercises the Prediction.fetch/2 path
    # (MF2: caller revert to own Map.fetch would break the atom-key
    # lookup on this string-keyed prediction).
    pred = Dspy.Prediction.new(%{"response" => "Ans#1"})

    judge = Dspy.Evaluate.SemanticF1.new()
    metric_fn = Dspy.Evaluate.SemanticF1.metric(judge)

    judge1 = EchoJudge.new()

    score_loaded =
      Dspy.context([lm: judge1], fn ->
        metric_fn.(loaded_ex, pred)
      end)

    judge2 = EchoJudge.new()

    score_atom =
      Dspy.context([lm: judge2], fn ->
        metric_fn.(atom_ex, pred)
      end)

    # The EchoJudge scores 1.0 (Recall/precision echo the fields it got),
    # so both key shapes must score the same — even if the string path
    # blanks the values (that is what the prompt check catches).
    assert score_loaded == score_atom
    assert score_loaded == 1.0

    # And the judge's request carried the loaded values: the prompt's
    # ground_truth is the loaded response, the system_response is the
    # prediction's response (V1, pre-mortem 13).
    [prompt_loaded | _] = EchoJudge.prompts(judge1)
    [prompt_atom | _] = EchoJudge.prompts(judge2)

    assert prompt_loaded =~ "R#1"
    assert prompt_loaded =~ "Q#1"
    assert prompt_loaded =~ "Ans#1"
    assert prompt_loaded == prompt_atom
  end

  test "row 29: JSON numeric label {\"answer\": 2} + answer_exact_match raises ArgumentError (parity: upstream ValueError)" do
    json_path = write("numeric.json", Jason.encode!(%{"answer" => 2}))
