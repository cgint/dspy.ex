  test "row 34: C5 — the case ids in m1e_deviations.json equal the fixture cases where our observed result differs from upstream's" do
    # The deviation set is COMPUTED, not hard-coded: the fixture's
    # `loader_inputs` and `dataset` sections record each case's input (fed to
    # the loader here, so our code runs on the exact same text) and
    # upstream's outcome ({"value": ...} or {"raises": ...}). A fixture case
    # deviates when OUR outcome differs from upstream's:
    #   * raises where upstream returned a value;
    #   * returned a value where upstream raised;
    #   * both returned values that differ. That is a declared E2/E7
    #     deviation (upstream infers cell types per column; ours stay strings),
    #     or an E5 structural field (upstream adds dspy_uuid / dspy_* keys).
    # Raise-vs-raise is NOT a deviation here: E3/E4 parity means upstream
    # raises a pandas/KeyError/DatasetGenerationError while we raise
    # ArgumentError — that is the declared exception-type parity, and
    # m1e_deviations.json documents exactly it. So an undeclared new
    # deviation can never pass: the declared `fixture_case` set must equal
    # the set this test computes.
    deviations = Jason.decode!(File.read!(deviations_path()))

    computed =
      @fixture["loader_inputs"]
      |> Enum.flat_map(fn {section, entries} ->
        entries
        |> Enum.map(fn {name, entry} ->
          case_name = "#{section}/#{name}"

          {
            case_name,
            deviates?(our_loader_outcome(section, entry), upstream_outcome(entry["upstream"]))
          }
        end)
      end)
      |> Enum.concat(
        @fixture["dataset"]
        |> Enum.map(fn {name, entry} ->
          {
            "dataset/#{name}",
            deviates?(our_dataset_outcome(name, entry), upstream_outcome(entry["upstream"]))
          }
        end)
      )
      |> Enum.filter(fn {_case, dev} -> dev end)
      |> Enum.map(fn {case, _} -> case end)
      |> MapSet.new()

    declared = Enum.map(deviations, & &1["fixture_case"]) |> MapSet.new()

    assert computed == declared,
           "declared deviations #{MapSet.to_list(declared)} != computed #{MapSet.to_list(computed)}"

    # The file's case ids stay the stable contract ids.
    ids = Enum.map(deviations, & &1["case_id"]) |> MapSet.new()

    assert ids ==
             MapSet.new([
               "m1e_e2",
               "m1e_e3",
               "m1e_e4",
               "m1e_e5",
               "m1e_e6"
             ])

    # Every entry has the shape the contract decides (2026-10-03 ruling):
    # {case_id, fixture_case, upstream, ours, reason} as a list of case_id
    # entries.
    Enum.each(deviations, fn entry ->
      assert is_binary(entry["case_id"])
      assert is_binary(entry["fixture_case"])
      assert is_binary(entry["upstream"])
      assert is_binary(entry["ours"])
      assert is_binary(entry["reason"])
    end)
  end

  defp deviations_path, do: Path.expand("../fixtures/m1e_deviations.json", __DIR__)

  defp upstream_outcome(%{"value" => v}), do: {:value, v}
  defp upstream_outcome(%{"raises" => r}), do: {:raises, r}

  # Run OUR loader on the recorded input text/options.
  defp our_loader_outcome("csv", %{"text" => text, "options" => opts}) do
    path = write("dev_#{System.unique_integer([:positive])}.csv", text)

    try do
      {:value, row_values(Dspy.DataLoader.from_csv(path, keyword_opts(opts)))}
    rescue
      e -> {:raises, exception_name(e)}
    end
  end

  defp our_loader_outcome("json", %{"text" => text, "options" => opts}) do
    path = write("dev_#{System.unique_integer([:positive])}.json", text)

    try do
      {:value, row_values(Dspy.DataLoader.from_json(path, keyword_opts(opts)))}
    rescue
      e -> {:raises, exception_name(e)}
    end
  end

  # Run OUR Dataset on the recorded split rows.
  defp our_dataset_outcome("train", %{"inputs" => rows}) do
    try do
      {:value, row_values(Dspy.Dataset.train(Dspy.Dataset.new(train: rows)))}
    rescue
      e -> {:raises, exception_name(e)}
    end
  end

  defp our_dataset_outcome("train_size_negative", %{"inputs" => rows, "train_size" => size}) do
    try do
      {:value, row_values(Dspy.Dataset.train(Dspy.Dataset.new(train: rows, train_size: size)))}
    rescue
      e -> {:raises, exception_name(e)}
    end
  end

  defp keyword_opts(%{"fields" => fields}), do: [fields: fields]
  defp keyword_opts(_), do: []

  # Raise-vs-raise is not a deviation (declared exception-type parity), so
  # the raised class is only kept for the outcome shape, not compared.
  defp exception_name(%{__exception__: _}), do: "ArgumentError-or-Exception"

  # Two outcomes differ when one side raised and the other didn't, or both
  # returned values that differ (E5: upstream's rows carry dspy_uuid4 / dspy_*
  # structural fields; ours do not). Raise-vs-raise is a declared-parity
  # exception-type difference, not a result difference (see row 34).
  defp deviates?({:value, v1}, {:value, v2}), do: v1 != v2
  defp deviates?({:raises, _}, {:raises, _}), do: false
  defp deviates?({:raises, _}, {:value, _}), do: true
  defp deviates?({:value, _}, {:raises, _}), do: true
end
