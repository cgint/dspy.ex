  defp write(name, content) do
    path = Path.join(@tmp_dir, name)
    File.write!(path, content)
    path
  end

  defp fixture(key, subkey \\ nil) do
    value = @fixture

    if is_nil(subkey),
      do: Map.fetch!(value, key),
      else: Map.fetch!(value, subkey) |> Map.fetch!(key)
  end

  # The row values of a loader list as plain string-keyed maps (values as-is).
  defp row_values(examples) do
    Enum.map(examples, fn %Example{attrs: attrs} -> attrs end)
  end

  defp example_keys(%Example{attrs: attrs}), do: Map.keys(attrs)

  # A CSV file of 10 rows, values 0..9, header "v".
  defp ten_rows_csv do
    header = "v\n"

    body =
      0..9
      |> Enum.map(&to_string/1)
      |> Enum.join("\n")

    header <> body <> "\n"
  end

  # A JSONL file of 10 records, "v" = 0..9 (string values).
  defp ten_rows_jsonl do
    0..9
    |> Enum.map(fn i -> Jason.encode!(%{"v" => to_string(i)}) end)
    |> Enum.join("\n")
  end

  defp ten_rows do
    Dspy.DataLoader.from_json(ten_rows_jsonl_path())
  end

  defp ten_rows_jsonl_path do
    write("ten_rows.jsonl", ten_rows_jsonl())
  end

  # A CapturingLM that emits a Default-adapter-compatible completion for the
  # question -> answer signature and records the full request.
  defmodule CapLM do
    @behaviour Dspy.LM
    defstruct [:pid, :answer]

    def new(pid, answer), do: %__MODULE__{pid: pid, answer: answer}

    @impl true
    def generate(%{pid: pid, answer: answer}, req) do
      send(pid, {:req, req})

      {:ok,
       %{
         choices: [
           %{message: %{role: "assistant", content: "Answer: #{answer}"}, finish_reason: "stop"}
         ],
         usage: nil
       }}
    end

    @impl true
    def supports?(_lm, _feature), do: true
  end

  defp request_text(req) do
    req
    |> Map.get(:messages, [])
    |> Enum.map(fn message ->
      content = Map.get(message, :content) || Map.get(message, "content")

      cond do
        is_binary(content) ->
          content

        is_list(content) ->
          Enum.map_join(content, "", fn
            %{"type" => "text", "text" => t} -> t
            _ -> ""
          end)

        true ->
          inspect(content)
      end
    end)
    |> Enum.join("")
  end

