  test "row 6: reset_seeds(train_seed: 1) keeps train_size, dev/test seeds and sizes" do
    rows = Enum.map(0..19, fn i -> %{"v" => i} end)

    ds =
      Dspy.Dataset.new(
        train: rows,
        dev: rows,
        test: rows,
        eval_seed: 7,
        dev_size: 6,
        test_size: 4,
        train_size: 7
      )

    reset = Dspy.Dataset.reset_seeds(ds, train_seed: 1)
    # train now shuffles with seed 1: apply CPython Random(1).shuffle to indices 0..19, take 7.
    {state, _} = Dspy.Random.seed(1)
    {_s, shuffled} = Dspy.Random.shuffle(state, Enum.to_list(0..19))
    expected_train = Enum.take(shuffled, 7)
    # row_values(train) are maps with "v" => the integer at that index
    assert Enum.map(row_values(Dspy.Dataset.train(reset)), & &1["v"]) == expected_train
    # the other values kept:
    assert length(Dspy.Dataset.dev(reset)) == 6
    assert length(Dspy.Dataset.test(reset)) == 4
    assert row_values(Dspy.Dataset.dev(reset)) == row_values(Dspy.Dataset.dev(ds))
    assert row_values(Dspy.Dataset.test(reset)) == row_values(Dspy.Dataset.test(ds))
  end

