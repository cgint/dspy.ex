defmodule Dspy.Evaluate.AutoEvaluation.SignaturesTest do
  @moduledoc """
  M1-d SS2 (row 11): the four judge signatures' instructions, field names,
  field descriptions and field order equal upstream DSPy 3.4.0's, pinned by
  the committed golden `test/fixtures/upstream_m1d_auto_eval_3_4_0.json`
  (generated by `plan/research/upstream_golden/gen_m1d_golden.py`).

  Upstream type mapping: `str` -> `:string`, `float` -> `:number`.
  """
  use ExUnit.Case, async: true

  @fixture Path.expand("../../fixtures/upstream_m1d_auto_eval_3_4_0.json", __DIR__)
  @fixture_data Jason.decode!(File.read!(@fixture))

  @signatures [
    {"SemanticRecallPrecision", Dspy.Evaluate.AutoEvaluation.SemanticRecallPrecision},
    {"DecompositionalSemanticRecallPrecision",
     Dspy.Evaluate.AutoEvaluation.DecompositionalSemanticRecallPrecision},
    {"AnswerCompleteness", Dspy.Evaluate.AutoEvaluation.AnswerCompleteness},
    {"AnswerGroundedness", Dspy.Evaluate.AutoEvaluation.AnswerGroundedness}
  ]

  defp map_type(upstream) do
    case upstream do
      "str" -> :string
      "float" -> :number
      other -> flunk("unmapped upstream type #{inspect(other)} in golden")
    end
  end

  for {name, mod} <- @signatures do
    @name name
    @mod mod

    test "#{@name}: instruction matches the upstream golden (after String.trim)" do
      fixture = @fixture_data[@name]
      assert is_map(fixture), "golden is missing the #{inspect(@name)} entry"

      expected = String.trim(fixture["instruction"])

      assert is_binary(expected) and expected != "",
             "golden #{inspect(@name)}.instruction is missing or empty"

      got = String.trim(@mod.signature().instructions || "")

      assert got == expected,
             "#{@name} instruction drift:\n  golden: #{inspect(expected)}\n  ours:   #{inspect(got)}"
    end

    test "#{@name}: field names, order, types and descriptions match the upstream golden" do
      fixture = @fixture_data[@name]
      assert is_map(fixture), "golden is missing the #{inspect(@name)} entry"
      fixture_fields = fixture["fields"]

      assert is_list(fixture_fields) and fixture_fields != [],
             "golden #{inspect(@name)}.fields is missing or empty"

      # No vacuous asserts: the golden must name both directions and ours must
      # carry exactly the same field count.
      assert Enum.count(fixture_fields, & &1["is_input"]) >= 1,
             "golden #{inspect(@name)} has no input fields"

      assert Enum.count(fixture_fields, &(not &1["is_input"])) >= 1,
             "golden #{inspect(@name)} has no output fields"

      signature = @mod.signature()
      ours = signature.input_fields ++ signature.output_fields

      assert length(ours) == length(fixture_fields),
             "#{@name}: field count #{length(ours)} != golden #{length(fixture_fields)}"

      Enum.zip(ours, fixture_fields)
      |> Enum.each(fn {ours, golden} ->
        assert is_binary(golden["name"]),
               "golden #{inspect(@name)} field missing name: #{inspect(golden)}"

        assert ours.name == String.to_existing_atom(golden["name"]),
               "#{@name}: field name #{inspect(ours.name)} != golden #{inspect(golden["name"])}"

        assert ours.type == map_type(golden["type"]),
               "#{@name}: field #{inspect(ours.name)} type #{inspect(ours.type)} " <>
                 "!= golden #{inspect(golden["type"])}"

        assert is_binary(golden["desc"]),
               "golden #{inspect(@name)} field #{inspect(golden["name"])} missing desc"

        assert ours.description == golden["desc"],
               "#{@name}: field #{inspect(ours.name)} description " <>
                 "#{inspect(ours.description)} != golden #{inspect(golden["desc"])}"

        expected_input = golden["is_input"] == true
        actual_input = ours.name in Enum.map(signature.input_fields, & &1.name)

        assert actual_input == expected_input,
               "#{@name}: field #{inspect(ours.name)} direction mismatch " <>
                 "(ours input=#{actual_input}, golden is_input=#{inspect(expected_input)})"
      end)
    end
  end
end
