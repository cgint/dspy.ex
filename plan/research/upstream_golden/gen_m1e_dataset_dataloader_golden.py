#!/usr/bin/env python3
"""M1-e phase 2 golden fixture generator: CPython + upstream DSPy 3.4.0.

Produces `test/fixtures/upstream_m1e_dataset_dataloader_3_4_0.json`.

Every value in the fixture is computed by CPython (`random` module) or by
upstream DSPy 3.4.0 (`dspy.datasets.dataloader.DataLoader`,
`dspy.datasets.dataset.Dataset`). Nothing is transcribed by hand or
generated by Elixir. If Elixir disagrees with the fixture, Elixir is wrong.

Ruling 6 (2026-10-03): the train_test_split, Dataset.train and
prepare_by_seed vectors CALL upstream (a Dataset subclass / the DataLoader
method), not a CPython random re-implementation. `sample` stays
random.sample (upstream's DataLoader takes no seed; our `seed:` is an
extension).

Usage (the ONLY supported invocation — run from the upstream checkout):

    cd ../dspy-3.4.0 && uv run --with "datasets<3" \
        python /Users/cgint/dev-external/dspy.ex/plan/research/upstream_golden/gen_m1e_dataset_dataloader_golden.py

Writes: test/fixtures/upstream_m1e_dataset_dataloader_3_4_0.json
"""

import datetime
import io
import json
import os
import random
import sys
import tempfile
from pathlib import Path

ROOT = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else Path(__file__).resolve().parents[3]
OUT = ROOT / "test" / "fixtures" / "upstream_m1e_dataset_dataloader_3_4_0.json"


def first5(seed):
    r = random.Random(seed)
    return [r.getrandbits(32) for _ in range(5)]


def shuffled(seed, n):
    xs = list(range(n))
    random.Random(seed).shuffle(xs)
    return xs


def sampled(seed, n, k):
    return random.Random(seed).sample(range(n), k)


def example_value(ex):
    """Extract the value of the single data key from an upstream Example.

    Upstream Examples from the loaders have a single key (e.g. "v" or "id").
    We return that key's value so the fixture is JSON-serialisable and
    comparable on the Elixir side.
    """
    keys = list(ex.keys())
    if len(keys) != 1:
        raise ValueError(f"Expected exactly one key, got {keys}")
    return ex[keys[0]]


def example_values(examples):
    return [example_value(e) for e in examples]


def make_val_dataset_class(d, dl, n_rows):
    """Create a Dataset subclass whose _train/_dev/_test hold n_rows
    examples with key "v" = 0..n_rows-1.
    """
    from dspy.datasets.dataset import Dataset

    class _ValDataset(Dataset):
        def __init__(self, *args, **kwargs):
            super().__init__(*args, **kwargs)
            data = [{"v": i} for i in range(n_rows)]
            self._train = data
            self._dev = data
            self._test = data

    return _ValDataset


def tt_split_upstream(dl, examples, seed, train_size):
    """Ruling 6: CALL upstream's DataLoader.train_test_split.

    Upstream signature: train_test_split(dataset, train_size, test_size,
    random_state). dataset is a list[Example]. Returns a dict with
    'train' and 'test' keys, each a list[Example].
    """
    result = dl.train_test_split(examples, train_size=train_size, random_state=seed)
    return {"train": example_values(result["train"]), "test": example_values(result["test"])}


def csv_raw_cells(text):
    """Ruling 1: record CPython stdlib csv.reader raw cells (empty -> None)
    so the Elixir side compares against the RAW CELLS, not the pandas-typed
    upstream values."""
    import csv as _csv

    rows = list(_csv.reader(io.StringIO(text)))
    return [[None if c == "" else c for c in row] for row in rows]


def outcome_of(fn):
    """Run an upstream loader/dataset call and record its outcome as
    JSON-serialisable data.

    A normal outcome becomes {"value": <the rows/values>}; a raised outcome
    becomes {"raises": <the exception class name>} (e.g. "KeyError").
    Row order in the value is load order (dicts keep insertion order).
    """
    try:
        return {"value": fn()}
    except Exception as e:  # noqa: BLE001
        return {"raises": type(e).__name__}


def normalize_dataset_rows(examples):
    """dataset.train examples as plain dicts; dspy_uuid normalised to the
    literal "UUID" (it is a fresh random value every run, so the fixture must
    not carry it) while dspy_split is kept as a structural field. Upstream's
    dict() protocol HIDES dspy_* keys, so use keys(include_dspy=True) — the
    dspy_uuid present here is exactly the E5 deviation."""
    rows = []
    for e in examples:
        row = {k: e[k] for k in e.keys(include_dspy=True)}
        if "dspy_uuid" in row:
            row["dspy_uuid"] = "UUID"
        rows.append(row)
    return rows


def main():
    from dspy import Example
    from dspy.datasets.dataloader import DataLoader
    from dspy.datasets.dataset import Dataset

    dl = DataLoader()
    d = tempfile.mkdtemp()

    def w(name, text):
        p = os.path.join(d, name)
        with open(p, "w", newline="") as f:
            f.write(text)
        return p

    def rows(examples):
        return [dict(ex) for ex in examples]

    # (c2) row 34: the deviation file is computed by row 34 from this
    # `loader_inputs` table — every loader case's INPUT (the exact text fed
    # to the loader, plus the options) and UPSTREAM'S OUTCOME (its value, or
    # {"raises": type}). Nothing here is transcribed by hand.
    csv_input_cases = {
        "numbers": ("q,n,f,b\nx,2,1.5,True\ny,3,2.0,False\n", {}),
        "empty_cell_plus_quoted_empty": ('q,a\nx,\ny,""\n', {}),
        "short_row": ("q,a\nx\ny,z\n", {}),
        "long_row": ("q,a\nx,1,EXTRA\n", {}),
        "blank_line": ("q,a\nx,y\n\nz,w\n", {}),
        "dup_header": ("a,a\n1,2\n", {}),
        "bom": ("\ufeffq,a\nx,y\n", {}),
        "crlf_plus_embedded_newline": ('q,a\r\n"l1\nl2","say ""hi"""\r\n', {}),
        "fields_subset_order": ("q,a,z\nx,y,9\n", {"fields": ["a", "q"]}),
        "whitespace": ("q,a\n x , y \n", {}),
        # Unknown field: upstream raises KeyError('nope'); Elixir raises
        # ArgumentError naming it (declared parity of the raise, different
        # exception type — recorded as the upstream exception name).
        "unknown_field": ("q,a\nx,1\n", {"fields": ["nope"]}),
    }
    json_input_cases = {
        "array": (json.dumps([{"q": "x", "a": 1}, {"q": "y", "a": 2}]), {}),
        "jsonl": ('{"q":"x","a":1}\n{"q":"y","a":2}\n', {}),
        "jsonl_union_keys": ('{"q":"x","a":1}\n{"q":"y","b":true}\n', {}),
        "jsonl_nested": ('{"q":"x","m":{"k":[1,2]}}\n', {}),
        "jsonl_non_object": ('{"q":"x"}\n[1,2]\n', {}),
        "json_null": ('{"q":"x","a":null}\n', {}),
    }

    csv_cases = {}
    csv_loader_inputs = {}
    for name, (text, opts) in csv_input_cases.items():
        outcome = outcome_of(lambda: rows(dl.from_csv(w(name, text), **opts)))
        csv_loader_inputs[name] = {
            "text": text,
            "options": opts,
            "upstream": outcome,
        }
        csv_cases[name] = outcome

    json_cases = {}
    json_loader_inputs = {}
    for name, (text, opts) in json_input_cases.items():
        outcome = outcome_of(lambda: rows(dl.from_json(w(name, text), **opts)))
        json_loader_inputs[name] = {
            "text": text,
            "options": opts,
            "upstream": outcome,
        }
        json_cases[name] = outcome

    # --- Ruling 6: CALL upstream for train, dev, prepare_by_seed ---

    # row 7: shared eval_seed — a Dataset subclass with dev_size=6,
    # test_size=4, eval_seed=7 over 20 rows.
    ValDataset20 = make_val_dataset_class(d, dl, 20)
    ds7 = ValDataset20(dev_size=6, test_size=4, eval_seed=7)
    shared_eval_seed = {"seed7_n20": example_values(ds7.dev)}

    # row 8: Dataset.train seed 0, size 7 over 10 rows.
    ValDataset10 = make_val_dataset_class(d, dl, 10)
    ds8 = ValDataset10(train_size=7, train_seed=0)
    dataset_train = {"seed0_size7_n10": example_values(ds8.train)}

    # row 13: prepare_by_seed — classmethod on a Dataset subclass.
    # 50 dev rows, 100 train rows, 5 train seeds, dev_size=50, train_size=8.
    # prepare_by_seed creates a new instance via cls(**data_args), so the
    # subclass __init__ must accept the data_args kwargs.
    class _PbyDataset(Dataset):
        def __init__(self, *args, **kwargs):
            super().__init__(*args, **kwargs)
            self._train = [{"v": i} for i in range(100)]
            self._dev = [{"v": i} for i in range(50)]
            self._test = []

    pby_result = _PbyDataset.prepare_by_seed(
        train_seeds=[1, 2, 3, 4, 5],
        train_size=8,
        dev_size=50,
        eval_seed=2023,
    )
    # The full 50-element dev order at eval_seed 2023.
    # prepare_by_seed shuffles the dev data once with eval_seed, then cuts
    # it into slices. We record the full shuffled order so the Elixir side
    # can verify each slice is a contiguous window.
    full_dev_order = example_values(pby_result.eval_sets[0] + pby_result.eval_sets[1] + pby_result.eval_sets[2] + pby_result.eval_sets[3] + pby_result.eval_sets[4])
    prepare_by_seed = {
        "dev_seed2023_n50": full_dev_order,
        "train": {str(i + 1): example_values(pby_result.train_sets[i]) for i in range(5)},
    }

    # row 21b: train_test_split — CALL upstream's DataLoader.train_test_split
    # with a list of Examples (not a file path).
    from dspy import Example as _Ex

    examples10 = [_Ex(id=str(i)) for i in range(10)]
    train_test_split = {
        "n10_frac07_seed0": tt_split_upstream(dl, examples10, 0, 0.7),
        "n10_frac075_seed0": tt_split_upstream(dl, examples10, 0, 0.75),
        "n10_frac05_seed0": tt_split_upstream(dl, examples10, 0, 0.5),
        "n10_int5_seed1": tt_split_upstream(dl, examples10, 1, 5),
    }

    fixture = {
        "_meta": {
            "source": "CPython %s + dspy %s (datasets.load_dataset-backed loaders)"
            % (sys.version.split()[0], __import__("dspy").__version__),
            "python": sys.version,
            "generated": datetime.datetime.now(datetime.timezone.utc).isoformat(),
            "description": (
                "M1-e phase 2 golden: CPython random vectors and upstream DSPy 3.4.0 "
                "DataLoader loader outputs. Every value computed at generation time; "
                "see gen_m1e_dataset_dataloader_golden.py."
            ),
        },
        # row 3b / row 4b: DataLoader.sample golden vectors.
        "sample": {
            "n10_k3_seed0": sampled(0, 10, 3),
            "n10_k3_seed1": sampled(1, 10, 3),
            "n10_k3_seed2": sampled(2, 10, 3),
            "n8_k2_seed1": sampled(1, 8, 2),
            "n5_k2_seed3": sampled(3, 5, 2),
        },
        # row 7: dev and test share eval_seed.
        # Ruling 6: CALL upstream — a dspy.datasets.dataset.Dataset subclass
        # with dev_size/test_size/eval_seed, then dataset.dev.
        "shared_eval_seed": shared_eval_seed,
        # row 8: Dataset.train seed 0, size 7 over 10 rows.
        # Ruling 6: CALL upstream — a Dataset subclass, then dataset.train.
        "dataset_train": dataset_train,
        # row 13: prepare_by_seed vectors (upstream prepare_by_seed).
        # Ruling 6: CALL upstream Dataset.prepare_by_seed classmethod.
        "prepare_by_seed": prepare_by_seed,
        # row 14a-14j / 15-17: upstream CSV loader behaviour.
        "csv": csv_cases,
        # row 19a-19g: upstream JSON loader behaviour.
        "json": json_cases,
        # row 21b / row 21: train_test_split golden vectors.
        # Ruling 6: CALL upstream's DataLoader.train_test_split with a
        # list[Example], not a file path.
        "train_test_split": train_test_split,
        # (c2) row 34: per-loader-case inputs + upstream outcomes, so row 34
        # COMPUTES its deviation set instead of asserting a hand-written one.
        "loader_inputs": {"csv": csv_loader_inputs, "json": json_loader_inputs},
        # (c2) row 34: the two Dataset cases E5/E6 (not covered by the golden
        # rows above). The inputs are split rows the Dataset is constructed
        # from; `upstream` is what upstream's `dataset.train` does with them
        # (E5: every example gets a random dspy_uuid4 — recorded with the
        # uuid value normalised to the literal "UUID" so the fixture stays
        # deterministic; E6: a negative size slices off elements from the end,
        # Python slicing semantics).
        "dataset": {
            "train": {
                "inputs": [{"v": i} for i in range(10)],
                "upstream": {"value": normalize_dataset_rows(ds8.train)},
            },
            "train_size_negative": {
                "inputs": [{"v": i} for i in range(10)],
                "train_size": -1,
                "upstream": outcome_of(
                    lambda: normalize_dataset_rows(
                        ValDataset10(train_size=-1).train
                    )
                ),
            },
        },
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(fixture, indent=2) + "\n")
    print(f"Wrote {OUT}")
    print(f"  sample n10 k3 seed0 = {fixture['sample']['n10_k3_seed0']}")
    print(f"  dataset train seed0 size7 = {fixture['dataset_train']['seed0_size7_n10']}")
    print(
        f"  train_test_split n10 0.7 seed0 = "
        f"{fixture['train_test_split']['n10_frac07_seed0']}"
    )
    print(f"  csv numbers (upstream, typed) = {fixture['csv']['numbers']}")
    print(f"  json union keys (upstream) = {fixture['json']['jsonl_union_keys']}")
    print(
        f"  dataset E5/E6 outcomes = "
        f"{fixture['dataset']['train']['upstream']} / {fixture['dataset']['train_size_negative']['upstream']}"
    )
    print(f"  shared_eval_seed seed7 n20 = {fixture['shared_eval_seed']['seed7_n20']}")
    print(f"  prepare_by_seed dev = {fixture['prepare_by_seed']['dev_seed2023_n50']}")


if __name__ == "__main__":
    main()
