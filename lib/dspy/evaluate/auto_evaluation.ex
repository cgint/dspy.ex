defmodule Dspy.Evaluate.AutoEvaluation do
  @moduledoc """
  Judge signatures for LM-judged metrics (upstream `dspy.evaluate.auto_evaluation`,
  DSPy 3.4.0). The judge modules (`Dspy.Evaluate.SemanticF1`,
  `Dspy.Evaluate.CompleteAndGrounded`) build on these signatures.

  The instruction text, field names, field descriptions and field order equal
  upstream's, pinned by the golden
  `test/fixtures/upstream_m1d_auto_eval_3_4_0.json` (generated by
  `plan/research/upstream_golden/gen_m1d_golden.py` from dspy 3.4.0).
  Upstream `float` outputs are mapped to our `:number` type.
  """

  defmodule SemanticRecallPrecision do
    @moduledoc """
    Compare a system's response to the ground truth to compute its recall and precision. If asked to reason, enumerate key ideas in each response, and whether they are present in the other response.
    """
    use Dspy.Signature

    signature_instructions(
      "Compare a system's response to the ground truth to compute its recall and precision. If asked to reason, enumerate key ideas in each response, and whether they are present in the other response."
    )

    input_field(:question, :string, "${question}")
    input_field(:ground_truth, :string, "${ground_truth}")
    input_field(:system_response, :string, "${system_response}")

    output_field(
      :recall,
      :number,
      "fraction (out of 1.0) of ground truth covered by the system response"
    )

    output_field(
      :precision,
      :number,
      "fraction (out of 1.0) of system response covered by the ground truth"
    )
  end

  defmodule DecompositionalSemanticRecallPrecision do
    @moduledoc """
    Compare a system's response to the ground truth to compute recall and precision of key ideas. You will first enumerate key ideas in each response, discuss their overlap, and then report recall and precision.
    """
    use Dspy.Signature

    signature_instructions(
      "Compare a system's response to the ground truth to compute recall and precision of key ideas. You will first enumerate key ideas in each response, discuss their overlap, and then report recall and precision."
    )

    input_field(:question, :string, "${question}")
    input_field(:ground_truth, :string, "${ground_truth}")
    input_field(:system_response, :string, "${system_response}")

    output_field(:ground_truth_key_ideas, :string, "enumeration of key ideas in the ground truth")

    output_field(
      :system_response_key_ideas,
      :string,
      "enumeration of key ideas in the system response"
    )

    output_field(
      :discussion,
      :string,
      "discussion of the overlap between ground truth and system response"
    )

    output_field(
      :recall,
      :number,
      "fraction (out of 1.0) of ground truth covered by the system response"
    )

    output_field(
      :precision,
      :number,
      "fraction (out of 1.0) of system response covered by the ground truth"
    )
  end

  defmodule AnswerCompleteness do
    @moduledoc """
    Estimate the completeness of a system's responses, against the ground truth. You will first enumerate key ideas in each response, discuss their overlap, and then report completeness.
    """
    use Dspy.Signature

    signature_instructions(
      "Estimate the completeness of a system's responses, against the ground truth. You will first enumerate key ideas in each response, discuss their overlap, and then report completeness."
    )

    input_field(:question, :string, "${question}")
    input_field(:ground_truth, :string, "${ground_truth}")
    input_field(:system_response, :string, "${system_response}")

    output_field(:ground_truth_key_ideas, :string, "enumeration of key ideas in the ground truth")

    output_field(
      :system_response_key_ideas,
      :string,
      "enumeration of key ideas in the system response"
    )

    output_field(
      :discussion,
      :string,
      "discussion of the overlap between ground truth and system response"
    )

    output_field(
      :completeness,
      :number,
      "fraction (out of 1.0) of ground truth covered by the system response"
    )
  end

  defmodule AnswerGroundedness do
    @moduledoc """
    Estimate the groundedness of a system's responses, against real retrieved documents written by people. You will first enumerate whatever non-trivial or check-worthy claims are made in the system response, and then discuss the extent to which some or all of them can be deduced from the retrieved context and basic commonsense.
    """
    use Dspy.Signature

    signature_instructions(
      "Estimate the groundedness of a system's responses, against real retrieved documents written by people. You will first enumerate whatever non-trivial or check-worthy claims are made in the system response, and then discuss the extent to which some or all of them can be deduced from the retrieved context and basic commonsense."
    )

    input_field(:question, :string, "${question}")
    input_field(:retrieved_context, :string, "${retrieved_context}")
    input_field(:system_response, :string, "${system_response}")

    output_field(
      :system_response_claims,
      :string,
      "enumeration of non-trivial or check-worthy claims in the system response"
    )

    output_field(
      :discussion,
      :string,
      "discussion of how supported the claims are by the retrieved context"
    )

    output_field(
      :groundedness,
      :number,
      "fraction (out of 1.0) of system response supported by the retrieved context"
    )
  end
end
